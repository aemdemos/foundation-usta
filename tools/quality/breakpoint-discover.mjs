#!/usr/bin/env node
/**
 * breakpoint-discover.mjs — detect the SOURCE SITE's breakpoints and record them.
 *
 * This is a lift-and-shift migration project: we adopt the customer site's existing
 * breakpoints rather than imposing our own. Run this ONCE at the start of a migration
 * against a couple of representative pages (the homepage first), review the result,
 * and it writes tools/quality/breakpoints.json — the single source of truth that the
 * checker (breakpoint-check.mjs) and every developer then reuse.
 *
 * It reads local CSS files and/or fetches remote stylesheets, collects every distinct
 * `min-width` value used in a @media query, and reports them sorted. Pass --write to
 * persist. If nothing is found, it keeps the fallback defaults 600/900/1200.
 *
 * Usage:
 *   node tools/quality/breakpoint-discover.mjs https://example.com                 # fetch a page, scan its CSS
 *   node tools/quality/breakpoint-discover.mjs styles.css theme.css                # scan local CSS files
 *   node tools/quality/breakpoint-discover.mjs https://example.com --write         # also persist to breakpoints.json
 *   node tools/quality/breakpoint-discover.mjs https://a.com https://b.com --write # sample a couple of pages
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = process.cwd();
const DEFAULTS = [600, 900, 1200];

const rawArgs = process.argv.slice(2);
const write = rawArgs.includes('--write');
const inputs = rawArgs.filter((a) => a !== '--write');

if (!inputs.length) {
  console.error('Usage: node tools/quality/breakpoint-discover.mjs <page-url | css-file> [more…] [--write]');
  process.exit(2);
}

function extractMinWidths(css) {
  const found = new Set();
  // min-width: <n>px  and range syntax  width >= <n>px  /  <n>px <= width
  const re = /@media[^{]*?(?:min-width\s*:\s*|width\s*>=\s*|(\d+)px\s*<=\s*width)(\d+)?px?/gi;
  // Simpler, robust two-pass: scan @media prelude text for min-width-ish tokens.
  const media = css.match(/@media[^{]+/gi) || [];
  for (const m of media) {
    const lower = m.toLowerCase();
    const mins = [...lower.matchAll(/(?:min-width\s*:\s*|width\s*>=\s*|>=\s*)(\d+)px/g)];
    for (const g of mins) found.add(Number(g[1]));
    const rangeLe = [...lower.matchAll(/(\d+)px\s*<=\s*width/g)];
    for (const g of rangeLe) found.add(Number(g[1]));
  }
  return found;
}

async function fetchText(url) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url} → HTTP ${res.status}`);
  return res.text();
}

async function cssFromPage(url) {
  const html = await fetchText(url);
  const base = new URL(url);
  let css = '';
  // inline <style> blocks
  for (const m of html.matchAll(/<style[^>]*>([\s\S]*?)<\/style>/gi)) css += `\n${m[1]}`;
  // linked stylesheets
  const links = [...html.matchAll(/<link[^>]+rel=["']?stylesheet["']?[^>]*>/gi)]
    .map((l) => (l[0].match(/href=["']([^"']+)["']/i) || [])[1])
    .filter(Boolean);
  for (const href of links) {
    try {
      css += `\n${await fetchText(new URL(href, base).href)}`;
    } catch (e) {
      console.warn(`⚠ could not fetch ${href}: ${e.message}`);
    }
  }
  return css;
}

const all = new Set();
for (const input of inputs) {
  try {
    const css = /^https?:\/\//i.test(input)
      ? await cssFromPage(input)
      : readFileSync(join(ROOT, input), 'utf8');
    const bps = extractMinWidths(css);
    console.log(`  ${input} → ${bps.size ? [...bps].sort((a, b) => a - b).join(', ') : '(none found)'}`);
    for (const b of bps) all.add(b);
  } catch (e) {
    console.warn(`⚠ skipped ${input}: ${e.message}`);
  }
}

const discovered = [...all].sort((a, b) => a - b);
console.log(`\nDiscovered min-width breakpoints: ${discovered.length ? discovered.join(', ') : '(none)'}`);

if (!discovered.length) {
  console.log('No breakpoints detected — keeping fallback defaults 600/900/1200. Nothing written.');
  process.exit(0);
}

if (write) {
  const record = {
    $comment: 'SINGLE SOURCE OF TRUTH for this project\'s responsive breakpoints (lift-and-shift: adopted from the source site). See AGENTS.md → The Breakpoint Rule.',
    breakpoints: discovered,
    source: inputs.filter((i) => /^https?:\/\//i.test(i)).join(', ') || 'discovered-from-css',
    sampledPages: inputs,
    decidedOn: process.env.BREAKPOINT_DECIDED_ON || null,
    notes: 'Generated by breakpoint-discover.mjs. Fallback if empty: 600/900/1200.',
  };
  writeFileSync(join(ROOT, 'tools/quality/breakpoints.json'), `${JSON.stringify(record, null, 2)}\n`);
  console.log('✓ Wrote tools/quality/breakpoints.json — this is now the enforced set for the whole repo.');
} else {
  console.log('Review the values above, then re-run with --write to persist them to breakpoints.json.');
}
